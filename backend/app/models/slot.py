from datetime import datetime

from sqlmodel import CheckConstraint, Field, SQLModel, UniqueConstraint


class Slot(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    start_time: datetime
    end_time: datetime
    created_by: int = Field(foreign_key="user.id")  # the user who defined the slot


class SlotTable(SQLModel, table=True):
    # a table that is available in a slot: a slot offers one or more tables
    __tablename__ = "slot_table"
    __table_args__ = (
        UniqueConstraint("slot_id", "table_id"),
        CheckConstraint("occupied_seats >= 0", name="ck_slot_table_occupied_seats_non_negative"),
    )  # each table at most once per slot

    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    slot_id: int = Field(foreign_key="slot.id")
    table_id: int = Field(foreign_key="table.id")
    occupied_seats: int = Field(default=0)