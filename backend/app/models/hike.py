from datetime import datetime
from zoneinfo import ZoneInfo

from pydantic import field_validator, model_validator
from sqlmodel import CheckConstraint, Field, SQLModel, UniqueConstraint

HUT_TIMEZONE = ZoneInfo("Europe/Rome")


class Hike(SQLModel, table=True):
    __table_args__ = (
        CheckConstraint("expected_arrival > start_time", name="ck_hike_arrival_after_start"),
        CheckConstraint("duration_minutes > 0", name="ck_hike_duration_positive"),
    )

    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    hiker_id: int | None = Field(default=None, foreign_key="user.id")  # None: hike not tied to a hiker
    name: str
    destination_name: str
    # a hiker's hike has real times; a suggested hike has none, only the average duration
    start_time: datetime | None = None
    expected_arrival: datetime | None = None
    duration_minutes: int | None = None
    arrived: bool = False
    suggested: bool = False  # a suggested hike may only go through predefined points


class Point(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    name: str
    predefined: bool = False


class HikePoint(SQLModel, table=True):
    # a point the hike goes through: a hike has one or more points
    __tablename__ = "hike_point"
    __table_args__ = (UniqueConstraint("hike_id", "point_id"),)  # each point at most once per hike

    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    hike_id: int = Field(foreign_key="hike.id")
    point_id: int = Field(foreign_key="point.id")


class HikeTimes(SQLModel):
    # the times of a hiker's hike, shared by HikeCreate and HikeCopy
    start_time: datetime
    expected_arrival: datetime

    @field_validator("start_time", "expected_arrival")
    @classmethod
    def assume_hut_time(cls, value: datetime) -> datetime:
        # the db wants timezone-aware datetimes: a time sent without a timezone is the hut's local time
        if value.tzinfo is None:
            return value.replace(tzinfo=HUT_TIMEZONE)
        return value

    @model_validator(mode="after")
    def arrival_after_start(self):
        # same rule as the db check constraint, so the client gets a 422 instead of a 500
        if self.expected_arrival <= self.start_time:
            raise ValueError("expected_arrival must be after start_time")
        return self


class HikeCopy(HikeTimes):
    # what the hiker sends to follow a popular hike: which one, and the times of their own hike
    hike_id: int


class HikeCreate(HikeTimes):
    # what the client sends: arrived/suggested start as False and hiker_id is the logged-in user.
    # the times and their checks come from HikeTimes
    name: str
    destination_name: str
    point_ids: list[int] | None = None  # None or []: a hike without points of interest

    @field_validator("point_ids")
    @classmethod
    def no_duplicate_points(cls, point_ids: list[int] | None) -> list[int] | None:
        # the db allows each point at most once per hike
        if point_ids and len(set(point_ids)) != len(point_ids):
            raise ValueError("point_ids must not contain duplicates")
        return point_ids


class PopularHikeCreate(SQLModel):
    # what the staff sends: a suggested hike has no times and no hiker, only its average duration
    name: str
    destination_name: str
    duration_minutes: int = Field(gt=0)
    point_ids: list[int] = Field(min_length=1)  # only points of interest, at least one

    @field_validator("point_ids")
    @classmethod
    def no_duplicate_points(cls, point_ids: list[int]) -> list[int]:
        # the db allows each point at most once per hike
        if len(set(point_ids)) != len(point_ids):
            raise ValueError("point_ids must not contain duplicates")
        return point_ids


class PointCreate(SQLModel):
    # what the client sends: predefined is set by the endpoint, not by the client
    name: str

    @field_validator("name")
    @classmethod
    def name_not_blank(cls, name: str) -> str:
        name = name.strip()
        if not name:
            raise ValueError("name must not be empty")
        return name


class PointPublic(SQLModel):
    # plain copy of a Point: table objects lose their loaded fields when the session commits
    id: int
    name: str
    predefined: bool


class PopularHikePublic(SQLModel):
    # a suggested hike: a template with no times, only how long it takes on average
    id: int
    name: str
    destination_name: str
    duration_minutes: int
    points: list[PointPublic]


class HikePublic(SQLModel):
    # what the api sends back
    id: int
    hiker_id: int | None
    name: str
    destination_name: str
    start_time: datetime
    expected_arrival: datetime
    arrived: bool
    suggested: bool
    points: list[PointPublic]
