from datetime import datetime
from enum import Enum

from sqlmodel import Field, SQLModel


class Roles(str, Enum):  # str mixin: compares equal to plain strings and is JSON-serializable (JWT payload)
    HIKER = 'Hiker'
    WARDEN = 'Warden'
    EMPLOYEE = 'Employee'


class User(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    username: str
    name: str
    surname: str
    email: str = Field(unique=True)
    mobile_number: str
    notes: str | None = None
    emergency_contact: str | None = None
    password_hash: str  # Argon2id hash; it includes its own salt and parameters
    role: Roles = Roles.HIKER


class UserPublic(SQLModel):
    # what the api can show about a user: never the hash or the salt
    username: str
    role: Roles


class CurrentUser(UserPublic):
    # the logged-in user, read from the token. Only the id is unique: usernames can repeat
    id: int


class pwd_reset(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    user_id: int = Field(foreign_key="user.id")
    token_hash: str = Field(unique=True, index=True)  # sha256 of the token: the plain token is only sent to the user
    expire_at: datetime
    used: bool = False

class ResetData(SQLModel):
    token: str
    expire_at: datetime

class UserBookingCreation(SQLModel):
    id: int
    email: str
    role: Roles
