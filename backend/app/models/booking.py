from datetime import date, datetime, time, timezone

from sqlmodel import CheckConstraint, Field, SQLModel, UniqueConstraint


class Booking(SQLModel, table=True):
    __table_args__ = (
        CheckConstraint("party_size > 0", name="ck_booking_party_size_positive"),
    )

    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    user_id: int = Field(foreign_key="user.id")
    slot_id: int = Field(foreign_key="slot.id")
    party_size: int
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class BookingCreate(SQLModel):
    date: date
    time: time
    party_size: int = Field(gt=0)


class BookingUpdate(SQLModel):
    party_size: int = Field(gt=0)


class BookingTable(SQLModel, table=True):
    # the seats a booking uses on one of the tables of its slot: a booking uses one or more of them
    __tablename__ = "booking_table"
    __table_args__ = (
        UniqueConstraint("booking_id", "slot_table_id"),
        CheckConstraint("seats_booked > 0", name="ck_booking_table_seats_positive"),
    )  # each slot table at most once per booking

    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    booking_id: int = Field(foreign_key="booking.id")
    slot_table_id: int = Field(foreign_key="slot_table.id")
    seats_booked: int