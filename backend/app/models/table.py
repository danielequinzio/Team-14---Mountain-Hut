from sqlmodel import CheckConstraint, Field, SQLModel


class Table(SQLModel, table=True):
    __table_args__ = (
        CheckConstraint("capacity > 0", name="ck_table_capacity_positive"),
    )

    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    number: int = Field(unique=True)
    capacity: int
    location: str


class TableCreate(SQLModel):
    number: int = Field(gt=0)
    capacity: int = Field(gt=0)
    location: str = Field(min_length=1)


class SlotTablesAdd(SQLModel):
    table_ids: list[int] = Field(min_length=1)


class CopySlotRequest(SQLModel):
    target_slot_id: int = Field(gt=0)