from sqlmodel import CheckConstraint, Field, SQLModel


class Table(SQLModel, table=True):
    __table_args__ = (
        CheckConstraint("capacity > 0", name="ck_table_capacity_positive"),
    )

    id: int | None = Field(default=None, primary_key=True)  # generated by the db
    number: int = Field(unique=True)
    capacity: int
    location: str